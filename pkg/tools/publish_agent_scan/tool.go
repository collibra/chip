func validationError(message string) *Output {
	return &Output{Status: StatusValidationError, Message: message}
}

func domainClause(domainID string) string {
	if domainID == "" {
		return " and no domain (the environment's default applies)"
	}
	return fmt.Sprintf(" and domainId %q", domainID)
}

// typeSchemas advertises json.RawMessage as an object instead of an integer array.
func typeSchemas() map[reflect.Type]*jsonschema.Schema {
	return map[reflect.Type]*jsonschema.Schema{
		reflect.TypeFor[json.RawMessage](): {
			Type:        "object",
			Description: "The agent scan document, a JSON object.",
		},
	}
}
