// Package publish_agent_scan implements the publish_agent_scan MCP tool: it
// sends one agent scan document to Collibra (POST
// /rest/guardianFingerprint/v1/scans) as the calling user and returns the
// recorded scan. It never retries: every submission records a scan, so a
// repeated request would record it twice.
package publish_agent_scan

import (
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"net/http"
	"reflect"
	"strings"

	"github.com/collibra/chip/pkg/chip"
	"github.com/collibra/chip/pkg/clients"
	"github.com/google/jsonschema-go/jsonschema"
	"github.com/google/uuid"
	"github.com/modelcontextprotocol/go-sdk/mcp"
)

// OutputStatus is the outcome of a publish_agent_scan call.
type OutputStatus string

const (
	// StatusPreview means confirm was not set: nothing was sent.
	StatusPreview         OutputStatus = "preview"
	StatusSuccess         OutputStatus = "success"
	StatusValidationError OutputStatus = "validation_error"
	StatusError           OutputStatus = "error"
)

// Input is the tool's typed input.
type Input struct {
	Document   json.RawMessage `json:"document" jsonschema:"Required. The agent scan: the JSON object the agent-scanning skill produced, passed through as produced (do not edit, summarise or re-type it)."`
	ExternalID string          `json:"externalId" jsonschema:"Required. The agent's identifier, shaped '<telemetry route>:<instance>:<native id>' with the route in lowercase. The prefix is NOT a free label or a platform name: it tells Collibra where this agent's telemetry arrives, so do not invent one. Today the known route is 'databricks' (telemetry through the Databricks capability): 'databricks:<workspace id>:<catalog>.<schema>.<model>', e.g. 'databricks:1234567890123456:example_catalog.agents.support_triage_agent' (workspace id = the numeric Databricks workspace id, the rest = the Unity Catalog three-part model name). An agent with no telemetry route may use a free-form id. Must not contain '>', be blank, or start or end with whitespace."`
	DomainID   string          `json:"domainId,omitempty" jsonschema:"Optional. UUID of the Collibra domain (a folder-like container for assets) in which assets created by this scan are filed. Omit to use the environment's default."`
	Confirm    bool            `json:"confirm,omitempty" jsonschema:"Safety checkpoint. false (default) returns a PREVIEW of exactly what would be sent and sends NOTHING. Set true only after the user has clearly agreed to send this agent scan to Collibra."`
}

// Preview echoes every field that confirm=true will send.
type Preview struct {
	Document      json.RawMessage `json:"document" jsonschema:"The scan document that will be sent, exactly as supplied."`
	DocumentBytes int             `json:"documentBytes" jsonschema:"Size of the document in bytes."`
	ExternalID    string          `json:"externalId" jsonschema:"The external id that will be sent."`
	DomainID      string          `json:"domainId,omitempty" jsonschema:"The domain UUID that will be sent; absent when none was given."`
}

// Output is the typed response.
type Output struct {
	Status        OutputStatus `json:"status" jsonschema:"'preview' when confirm was not set (nothing sent; ask the user, then call again with confirm=true); 'success' when Collibra recorded the scan; 'validation_error' for bad inputs (nothing sent); 'error' when the scan was not recorded."`
	Message       string       `json:"message" jsonschema:"Plain-language summary that can be relayed to the customer."`
	Guidance      string       `json:"guidance,omitempty" jsonschema:"What to tell or ask the customer next, on error."`
	ErrorCode     string       `json:"errorCode,omitempty" jsonschema:"Machine-readable error code from Collibra (e.g. 'fingerprintDuplicateName'), when the request was rejected."`
	HTTPStatus    int          `json:"httpStatus,omitempty" jsonschema:"HTTP status of the rejection, when Collibra answered."`
	Warnings      []string     `json:"warnings,omitempty" jsonschema:"Non-blocking problems worth raising with the user, e.g. an externalId that does not match the platform details in the scan document. Returned with the preview and with the result."`
	Preview       *Preview     `json:"preview,omitempty" jsonschema:"What would be sent, returned when confirm=false."`
	ScanID        string       `json:"scanId,omitempty" jsonschema:"Id of the scan Collibra recorded, on success."`
	FingerprintID string       `json:"fingerprintId,omitempty" jsonschema:"Id of the agent version (one distinct state of the agent) the scan reported, on success. May be an existing version if nothing changed."`
	CreatedOn     string       `json:"createdOn,omitempty" jsonschema:"When Collibra recorded the scan (UTC, RFC 3339), on success."`
	GeneratedOn   string       `json:"generatedOn,omitempty" jsonschema:"When the scan document was generated by the producer (UTC, RFC 3339), on success."`
}

// NewTool returns the registered tool.
